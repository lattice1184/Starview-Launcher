    /// <summary>seen 版本之后的有名分组（不含历史组）——升级弹窗用；seen 为空返回空（首装不弹）</summary>
    public static IReadOnlyList<ChangelogGroup> GroupsAfter(string? seenVersion)
    {
        if (string.IsNullOrEmpty(seenVersion)) return [];
        return Groups
            .Where(g => g.Version != HistoricalVersion && VersionUtil.Compare(g.Version, seenVersion) > 0)
            .ToList();
    }

